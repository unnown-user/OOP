package ru.nsu.asemenychev.task112;

/**
 * Дилер — участник игры, действующий по фиксированным правилам.
 * Отличается от обычного Player тем, что обязан набирать
 * карты, пока сумма его очков меньше 17, и обязан остановиться,
 * как только она станет 17 или больше.
 */
public class Dealer extends Player {

    /**
     * Решает, должен ли дилер взять ещё одну карту.
     *
     * @return true, если сумма очков меньше 17
     */
    public boolean shouldHit() {
        return getHand().total() < 17;
    }
}